export function initialSummaryPrompt(
  task: ContextTaskKind,
  instructions?: string
): string {
  return [
    "上面 <conversation> 中是需要整理的对话。请生成结构化检查点。",
    TASK_FOCUS[task],
    instructions ? `用户特别要求保留：${instructions}` : "",
    FORMAT
  ]
    .filter(Boolean)
    .join("\n\n");
}

export function updateSummaryPrompt(
  task: ContextTaskKind,
  instructions?: string
): string {
  return [
    "上面 <conversation> 中是新的对话内容，<previous-summary> 中是之前的检查点。请把新内容合并进检查点：",
    "- 保留之前检查点中的全部信息，尤其是“用户硬约束与偏好”和“被否决的方案”；",
    "- 加入新的进展、决定和约束；把已完成的事项从“进行中”移到“已完成”；",
    "- 根据最新进展更新“下一步”；确已过时的信息可以删除。",
    TASK_FOCUS[task],
    instructions ? `用户特别要求保留：${instructions}` : "",
    FORMAT
  ]
    .filter(Boolean)
    .join("\n\n");
}

